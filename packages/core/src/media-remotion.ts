const EXCALIDRAW_FONT_SOURCE = ['@excalidraw', 'excalidraw', 'dist', 'prod', 'fonts'];

async function prepareRuntime(root: string, content: ContentIR): Promise<() => Promise<void>> {
  const dependencies = path.join(root, 'node_modules');
  let temporaryDependencies = false;
  const installed = path.join(REPOSITORY_ROOT, 'template', 'node_modules');
  if (!existsSync(dependencies)) {
    const declared = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')) as {
      dependencies: Record<string, string>; devDependencies: Record<string, string>;
    };
    for (const [name, version] of Object.entries({ ...declared.dependencies, ...declared.devDependencies })) {
      const installedPackage = path.join(installed, ...name.split('/'), 'package.json');
      if (!existsSync(installedPackage) || JSON.parse(await readFile(installedPackage, 'utf8')).version !== version) {
        throw new Error(`mp4_dependency_unavailable: ${name}@${version}; install generated package dependencies or restore template/node_modules`);
      }
    }
    await mkdir(dependencies);
    temporaryDependencies = true;
  }
  const cleanup = async () => {
    if (temporaryDependencies) await rm(dependencies, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 });
  };
  try {
    if (temporaryDependencies) {
      // Share packages, never the mutable Webpack cache used by concurrent project renders.
      for (const entry of readdirSync(installed, { withFileTypes: true })) {
        if (entry.isDirectory() && entry.name !== '.cache' && entry.name !== '.remotion') {
          symlinkSync(path.join(installed, entry.name), path.join(dependencies, entry.name), process.platform === 'win32' ? 'junction' : 'dir');
        }
      }
    }
    if (content.sections.some((section) => section.visual?.kind === 'excalidraw')) {
      const source = path.join(installed, ...EXCALIDRAW_FONT_SOURCE);
      if (!existsSync(source)) throw new Error('excalidraw_fonts_unavailable: restore template/node_modules');
      // Xiaolai is a 12 MB CJK face; the pipeline is English-only.
      cpSync(source, path.join(root, 'public', 'excalidraw', 'fonts'), { recursive: true, filter: (file) => !file.includes(`${path.sep}Xiaolai`) });
    }
  } catch (error) {
    await cleanup();
    throw error;
  }
  return cleanup;
}

// Deep release folders push a junctioned browser path past the Windows process-path limit; launch the shared browser by its real path.
function sharedBrowserExecutable(): string | undefined {
  const base = path.join(REPOSITORY_ROOT, 'template', 'node_modules', '.remotion', 'chrome-headless-shell');
  if (!existsSync(base)) return undefined;
  const name = process.platform === 'win32' ? 'chrome-headless-shell.exe' : 'chrome-headless-shell';
  for (const platform of readdirSync(base, { withFileTypes: true }).filter((entry) => entry.isDirectory())) {
    for (const build of readdirSync(path.join(base, platform.name), { withFileTypes: true }).filter((entry) => entry.isDirectory())) {
      const candidate = path.join(base, platform.name, build.name, name);
      if (existsSync(candidate)) return candidate;
    }
  }
  return undefined;
}

function remotionCli(root: string, args: string[], label: string, timeout: number, port?: number): void {
  const browser = sharedBrowserExecutable();
  const result = spawnSync(process.execPath, [path.join('node_modules', '@remotion', 'cli', 'remotion-cli.js'), ...args,
    ...(browser ? [`--browser-executable=${browser}`] : []), ...(port ? [`--port=${port}`] : [])], {
    cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, timeout, windowsHide: true
  });
  if (result.error || result.status !== 0) {
    throw new Error(`${label}: ${result.error?.message ?? (result.stderr || result.stdout).trim().slice(-4000)}`);
  }
}

// Concurrent renders must not share Remotion's default bundle-server port 3000, or one render's browser loads another render's chunks.
// Ports come from 20000-29999, below the Windows dynamic range where Hyper-V reserves blocks, and must be free on every host Remotion tests.
async function freePort(): Promise<number> {
  const free = (port: number, host: string) => new Promise<boolean>((resolve) => {
    const server = createServer();
    server.unref();
    server.once('error', (error: NodeJS.ErrnoException) => resolve(['EADDRNOTAVAIL', 'EAFNOSUPPORT'].includes(error.code ?? '')));
    server.listen({ port, host, exclusive: true }, () => server.close(() => resolve(true)));
  });
  for (let attempt = 0; attempt < 64; attempt += 1) {
    const port = 20000 + randomInt(10000);
    let available = true;
    for (const host of ['::1', '127.0.0.1', '::', '0.0.0.0']) if (!(await free(port, host))) { available = false; break; }
    if (available) return port;
  }
  throw new Error('free_port_unavailable');
}

