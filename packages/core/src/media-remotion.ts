function color(value) {
  const clamped = Math.max(0, Math.min(1, value));
  const r = Math.round(17 + clamped * 210);
  const g = Math.round(24 + Math.sin(clamped * Math.PI) * 150);
  const b = Math.round(39 + (1 - clamped) * 170);
  return 'rgb(' + r + ',' + g + ',' + b + ')';
}

